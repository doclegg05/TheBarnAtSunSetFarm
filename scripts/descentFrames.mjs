// Turns the opening drone descent into the still frames the /experience page
// scrubs through as you scroll (components/experience/descent.ts).
//
//   node scripts/descentFrames.mjs path/to/descent.mp4
//
// Needs ffmpeg on the PATH; sharp is already a dev dependency. Writes AVIF
// frames to public/descent/{sm,md}/ and their count to
// components/experience/descentFrames.ts. The source video is AI-generated
// (ElevenLabs Flows); see videos/descent/NOTES.md.

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import sharp from 'sharp';

const FPS = 10;
const SIZES = {
  sm: { width: 640, quality: 42 },
  md: { width: 1024, quality: 40 },
};

const source = process.argv[2];
if (!source || !fs.existsSync(source)) {
  console.error('Usage: node scripts/descentFrames.mjs path/to/descent.mp4');
  process.exit(1);
}

const root = path.resolve(
  path.dirname(new URL(import.meta.url).pathname),
  '..'
);
const outDir = path.join(root, 'public/descent');
const work = fs.mkdtempSync(path.join(os.tmpdir(), 'descent-'));

execFileSync('ffmpeg', [
  '-loglevel',
  'error',
  '-i',
  source,
  '-vf',
  `fps=${FPS},scale=${SIZES.md.width}:-2`,
  path.join(work, '%03d.png'),
]);
const frames = fs
  .readdirSync(work)
  .filter((f) => f.endsWith('.png'))
  .sort();

for (const [name, { width, quality }] of Object.entries(SIZES)) {
  const dir = path.join(outDir, name);
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir, { recursive: true });
  let bytes = 0;
  // AVIF encoding is slow and mostly single-threaded: one frame per core.
  const queue = [...frames.entries()];
  const encode = async () => {
    for (let job = queue.shift(); job; job = queue.shift()) {
      const [i, frame] = job;
      const data = await sharp(path.join(work, frame))
        .resize({ width })
        .avif({ quality, effort: 4 })
        .toBuffer();
      fs.writeFileSync(
        path.join(dir, `${String(i).padStart(3, '0')}.avif`),
        data
      );
      bytes += data.length;
    }
  };
  await Promise.all(Array.from({ length: os.cpus().length }, encode));
  console.log(
    `${name}: ${frames.length} frames, ${(bytes / 1e6).toFixed(1)} MB`
  );
}

const { height } = await sharp(path.join(work, frames[0])).metadata();
fs.writeFileSync(
  path.join(root, 'components/experience/descentFrames.ts'),
  `// Generated by scripts/descentFrames.mjs. Do not edit by hand.
export const DESCENT_FRAMES = {
  count: ${frames.length},
  fps: ${FPS},
  aspect: ${(SIZES.md.width / height).toFixed(4)},
  sizes: { sm: ${SIZES.sm.width}, md: ${SIZES.md.width} },
} as const;
`
);
fs.rmSync(work, { recursive: true, force: true });
