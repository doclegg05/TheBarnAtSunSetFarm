// Turns a film master (the drone descent, the walk into the barn) into what
// the /experience page plays on a tap (components/experience/TapFilm.tsx):
//
//   node scripts/filmVideos.mjs path/to/master.mp4 <name> [--grade '<json>'] [--still <seconds>]
//
// Writes, to public/films/<name>/:
//   landscape.mp4  1920x1080 H.264, for screens wider than tall
//   portrait.mp4   1080x1920 H.264, the upright middle of the frame
//   first-{landscape,portrait}.avif, last-{...}.avif  the opening and closing frames
//   still-{...}.avif  a frame at --still seconds, when given (a poster)
// and the film's length and sizes to components/experience/films/<name>.ts.
// --grade takes the JSON scripts/fitGrade.mjs prints. Needs ffmpeg with
// libx264; sharp is a dev dependency. Masters: videos/descent/NOTES.md,
// videos/film/INSIDE.md.

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import sharp from 'sharp';

const args = process.argv.slice(2);
const option = (flag) => {
  const at = args.indexOf(flag);
  return at >= 0 ? args.splice(at, 2)[1] : undefined;
};
const grade = option('--grade');
const still = option('--still');
const [source, name] = args;
if (!source || !fs.existsSync(source) || !/^[a-z-]+$/.test(name ?? '')) {
  console.error(
    "Usage: node scripts/filmVideos.mjs master.mp4 <name> [--grade '<json>'] [--still <seconds>]"
  );
  process.exit(1);
}

const root = path.resolve(
  path.dirname(new URL(import.meta.url).pathname),
  '..'
);
const outDir = path.join(root, 'public', 'films', name);
fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });

/** ffmpeg's lutrgb for a per-channel gain and offset, as fitGrade measures. */
const gradeFilter = () => {
  if (!grade) return [];
  const { gain, offset } = JSON.parse(grade);
  const channel = (c, i) => `${c}='clip(val*${gain[i]}+${offset[i]},0,255)'`;
  return [`lutrgb=${['r', 'g', 'b'].map(channel).join(':')}`];
};

const SHAPES = {
  landscape: { width: 1920, height: 1080, crop: [] },
  portrait: { width: 1080, height: 1920, crop: ['crop=ih*9/16:ih'] },
};

const filterFor = (shape) =>
  [
    ...gradeFilter(),
    ...shape.crop,
    `scale=${shape.width}:${shape.height}:flags=lanczos`,
    'format=yuv420p',
  ].join(',');

const duration = Number(
  execFileSync('ffprobe', [
    '-v',
    'error',
    '-show_entries',
    'format=duration',
    '-of',
    'csv=p=0',
    source,
  ])
    .toString()
    .trim()
);

const encode = (key, shape) => {
  const file = path.join(outDir, `${key}.mp4`);
  execFileSync('ffmpeg', [
    '-loglevel',
    'error',
    '-i',
    source,
    '-vf',
    filterFor(shape),
    '-an',
    '-c:v',
    'libx264',
    '-profile:v',
    'high',
    '-preset',
    'slow',
    '-crf',
    '24',
    '-movflags',
    '+faststart',
    file,
  ]);
  console.log(`${key}.mp4: ${(fs.statSync(file).size / 1e6).toFixed(1)} MB`);
};

const grab = async (key, shape, at, label) => {
  const png = path.join(os.tmpdir(), `${name}-${label}-${key}.png`);
  execFileSync('ffmpeg', [
    '-loglevel',
    'error',
    '-y',
    // The last frame is found from the end; any other by its time.
    ...(at === 'end' ? ['-sseof', '-0.1'] : ['-ss', String(at)]),
    '-i',
    source,
    '-frames:v',
    '1',
    '-vf',
    filterFor(shape),
    png,
  ]);
  await sharp(png)
    .avif({ quality: 50, effort: 4 })
    .toFile(path.join(outDir, `${label}-${key}.avif`));
  fs.rmSync(png);
};

for (const [key, shape] of Object.entries(SHAPES)) {
  encode(key, shape);
  await grab(key, shape, 0, 'first');
  await grab(key, shape, 'end', 'last');
  if (still) await grab(key, shape, Number(still), 'still');
}

fs.writeFileSync(
  path.join(root, `components/experience/films/${name}.ts`),
  `// Generated by scripts/filmVideos.mjs. Do not edit by hand.
export default {
  name: '${name}',
  duration: ${Number(duration.toFixed(3))},
  stills: [${['first', 'last', ...(still ? ['still'] : [])].map((s) => `'${s}'`).join(', ')}],
} as const;
`
);
console.log(`${name}: ${duration.toFixed(2)} s`);
